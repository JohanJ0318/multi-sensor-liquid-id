static uint16_t Conductivity_Read(uint16_t sample_count)
{
    uint32_t sum = 0U;
    uint16_t minimum = 4095U;
    uint16_t maximum = 0U;

    if (sample_count < 3U)
    {
        return 0U;
    }

    /*
     * Force the divider node to a known discharged state
     * before beginning each measurement.
     */
    HAL_GPIO_WritePin(COND_IN_GPIO_Port,
                      COND_IN_Pin,
                      GPIO_PIN_RESET);

    HAL_Delay(10);

    /*
     * Apply excitation and allow the divider and ADC node
     * to settle completely.
     */
    HAL_GPIO_WritePin(COND_IN_GPIO_Port,
                      COND_IN_Pin,
                      GPIO_PIN_SET);

    HAL_Delay(10);

    /* Discard initial ADC conversions. */
    (void)ADC_ReadSingle(&hadc1);
    (void)ADC_ReadSingle(&hadc1);
    (void)ADC_ReadSingle(&hadc1);

    for (uint16_t i = 0U; i < sample_count; i++)
    {
        uint16_t sample = ADC_ReadSingle(&hadc1);

        sum += sample;

        if (sample < minimum)
        {
            minimum = sample;
        }

        if (sample > maximum)
        {
            maximum = sample;
        }
    }

    HAL_GPIO_WritePin(COND_IN_GPIO_Port,
                      COND_IN_Pin,
                      GPIO_PIN_RESET);

    sum -= minimum;
    sum -= maximum;

    return (uint16_t)(sum / (sample_count - 2U));
}

/*
 * Convert raw conductivity ADC counts to mS/cm using the two-point
 * calibrated model sigma = A*r/(1 - B*r), r = adc/(4095-adc). The B
 * term corrects the saturation from series/electrode resistance. Near
 * and past the model's asymptote the value is clamped, so very
 * conductive liquids report a large, stable ceiling instead of a
 * divergent number. Result is compensated to 25 C (~2%/C).
 */
static float Conductivity_ToMScm(uint16_t adc, float temp_c)
{
    float r;
    float denom;
    float sigma;

    if (adc >= 4095U)
    {
        return -1.0f;  /* railed - not a valid reading */
    }

    r = (float)adc / (4095.0f - (float)adc);

    denom = 1.0f - (COND_CAL_B * r);

    if (denom < 0.05f)
    {
        denom = 0.05f;  /* at/past the asymptote: peg the reading */
    }

    sigma = (COND_CAL_A_MS_CM * r) / denom;

    if (sigma > COND_MAX_MS_CM)
    {
        sigma = COND_MAX_MS_CM;
    }

    return sigma / (1.0f + 0.02f * (temp_c - 25.0f));
}
