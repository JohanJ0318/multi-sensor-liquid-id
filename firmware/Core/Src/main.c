/*
 * Tare the load cell: average readings for duration_ms into
 * load_zero_adc. Runs on every boot (power-up or app RESET), so the
 * chamber must be empty - or hold only the empty vessel - during it.
 * The OLED stays off while sampling, same precaution as measurements.
 */
static void LoadCell_Tare(uint32_t duration_ms)
{
    uint32_t start_ms;
    float sum = 0.0f;
    uint32_t count = 0U;
    char buffer[64];

    OLED_Command(0xAF);
    OLED_Clear();
    OLED_WriteLine(2U, "TARING");
    HAL_Delay(150U);

    OLED_Command(0xAE);
    HAL_Delay(50U);

    start_ms = HAL_GetTick();

    while ((HAL_GetTick() - start_ms) < duration_ms)
    {
        sum += (float)LoadCell_ReadFiltered(32U);
        count++;
    }

    if (count > 0U)
    {
        load_zero_adc = sum / (float)count;
    }

    snprintf(buffer,
             sizeof(buffer),
             "TARE | ZERO:%.1f | N:%lu\r\n",
             load_zero_adc,
             (unsigned long)count);

    BT_SendString(buffer);
}

static float MedianFloat(float values[], uint16_t count)
{
    if ((values == NULL) || (count == 0U))
    {
        return 0.0f;
    }

    /*
     * Insertion sort is appropriate for this small array.
     * The original array is intentionally sorted in place.
     */
    for (uint16_t i = 1U; i < count; i++)
    {
        float current = values[i];
        int32_t j = (int32_t)i - 1;

        while ((j >= 0) && (values[j] > current))
        {
            values[j + 1] = values[j];
            j--;
        }

        values[j + 1] = current;
    }

    if ((count & 1U) != 0U)
    {
        return values[count / 2U];
    }

    return (values[(count / 2U) - 1U] +
            values[count / 2U]) / 2.0f;
}

static uint16_t MedianUint16(uint16_t values[], uint16_t count)
{
    if ((values == NULL) || (count == 0U))
    {
        return 0U;
    }

    for (uint16_t i = 1U; i < count; i++)
    {
        uint16_t current = values[i];
        int32_t j = (int32_t)i - 1;

        while ((j >= 0) && (values[j] > current))
        {
            values[j + 1] = values[j];
            j--;
        }

        values[j + 1] = current;
    }

    if ((count & 1U) != 0U)
    {
        return values[count / 2U];
    }

    return (uint16_t)(
        ((uint32_t)values[(count / 2U) - 1U] +
         (uint32_t)values[count / 2U]) / 2U);
}

