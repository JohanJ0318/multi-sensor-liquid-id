#!/usr/bin/env python3
"""
train_models.py — Offline model training for the Liquid ID system.

Reads reference measurement CSV data, trains kNN and nearest-centroid
classifiers, and exports model parameters as C header arrays for
deployment to the STM32.

Usage:
    python train_models.py --data ../test-data/reference_measurements.csv
    python train_models.py --data ../test-data/reference_measurements.csv --k 5 --output ../firmware/Core/Inc/model_params.h
"""

import argparse
import csv
import sys
import numpy as np
from pathlib import Path


def load_reference_data(filepath: str):
    """Load CSV with columns: label, conductivity_ms_cm, density_g_ml, temperature_c"""
    labels = []
    features = []

    with open(filepath, "r") as f:
        reader = csv.DictReader(f)
        for row in reader:
            labels.append(row["label"].strip())
            features.append([
                float(row["conductivity_ms_cm"]),
                float(row["density_g_ml"]),
                float(row["temperature_c"]),
            ])

    return np.array(features), labels


def compute_centroids(features: np.ndarray, labels: list):
    """Compute per-class centroid vectors."""
    unique_labels = sorted(set(labels))
    centroids = []
    for label in unique_labels:
        mask = [l == label for l in labels]
        class_features = features[mask]
        centroids.append(class_features.mean(axis=0))
    return np.array(centroids), unique_labels


def export_c_header(
    filepath: str,
    ref_vectors: np.ndarray,
    ref_labels_encoded: np.ndarray,
    centroids: np.ndarray,
    centroid_label_indices: list,
    unique_labels: list,
    norm_means: np.ndarray,
    norm_stds: np.ndarray,
    k: int,
):
    """Write model parameters as a C header file."""
    n_ref, n_feat = ref_vectors.shape
    n_classes = len(unique_labels)

    with open(filepath, "w") as f:
        f.write("/**\n")
        f.write(" * @file    model_params.h\n")
        f.write(" * @brief   Auto-generated classification model parameters\n")
        f.write(f" * @note    {n_ref} reference vectors, {n_classes} classes, k={k}\n")
        f.write(" *\n")
        f.write(" * Generated by train_models.py — DO NOT EDIT MANUALLY\n")
        f.write(" */\n\n")
        f.write("#ifndef __MODEL_PARAMS_H\n#define __MODEL_PARAMS_H\n\n")
        f.write(f"#define MODEL_REF_COUNT     {n_ref}\n")
        f.write(f"#define MODEL_FEAT_DIM      {n_feat}\n")
        f.write(f"#define MODEL_CLASS_COUNT   {n_classes}\n")
        f.write(f"#define MODEL_KNN_K         {k}\n\n")

        # Substance labels
        f.write("static const char *MODEL_SUBSTANCE_LABELS[] = {\n")
        for label in unique_labels:
            f.write(f'    "{label}",\n')
        f.write("};\n\n")

        # Normalization parameters
        f.write("static const float MODEL_NORM_MEANS[] = {\n    ")
        f.write(", ".join(f"{v:.6f}f" for v in norm_means))
        f.write("\n};\n\n")

        f.write("static const float MODEL_NORM_STDS[] = {\n    ")
        f.write(", ".join(f"{v:.6f}f" for v in norm_stds))
        f.write("\n};\n\n")

        # kNN reference vectors (normalized)
        f.write(f"static const float MODEL_KNN_VECTORS[{n_ref * n_feat}] = {{\n")
        for i, vec in enumerate(ref_vectors):
            vals = ", ".join(f"{v:.6f}f" for v in vec)
            f.write(f"    {vals},  /* [{i}] */\n")
        f.write("};\n\n")

        # kNN reference labels
        f.write(f"static const uint8_t MODEL_KNN_LABELS[{n_ref}] = {{\n    ")
        f.write(", ".join(str(int(l)) for l in ref_labels_encoded))
        f.write("\n};\n\n")

        # Nearest-centroid vectors (normalized)
        f.write(f"static const float MODEL_NC_CENTROIDS[{n_classes * n_feat}] = {{\n")
        for i, vec in enumerate(centroids):
            vals = ", ".join(f"{v:.6f}f" for v in vec)
            f.write(f"    {vals},  /* {unique_labels[i]} */\n")
        f.write("};\n\n")

        # Centroid label indices
        f.write(f"static const uint8_t MODEL_NC_LABELS[{n_classes}] = {{\n    ")
        f.write(", ".join(str(i) for i in centroid_label_indices))
        f.write("\n};\n\n")

        f.write("#endif /* __MODEL_PARAMS_H */\n")

    print(f"Exported model parameters to {filepath}")


def main():
    parser = argparse.ArgumentParser(description="Train Liquid ID classifiers")
    parser.add_argument("--data", required=True, help="Path to reference CSV")
    parser.add_argument("--k", type=int, default=5, help="kNN k value")
    parser.add_argument("--output", default="model_params.h", help="Output header path")
    args = parser.parse_args()

    if not Path(args.data).exists():
        print(f"Error: data file not found: {args.data}", file=sys.stderr)
        sys.exit(1)

    print(f"Loading data from {args.data}...")
    features, labels = load_reference_data(args.data)
    print(f"  {len(labels)} samples, {len(set(labels))} classes")

    # Encode labels to integer indices
    unique_labels = sorted(set(labels))
    label_to_idx = {l: i for i, l in enumerate(unique_labels)}
    labels_encoded = np.array([label_to_idx[l] for l in labels])

    # Compute normalization parameters
    norm_means = features.mean(axis=0)
    norm_stds = features.std(axis=0)
    norm_stds[norm_stds < 1e-8] = 1.0  # Prevent division by zero

    # Normalize
    features_norm = (features - norm_means) / norm_stds

    # Compute centroids (on normalized data)
    centroids, _ = compute_centroids(features_norm, labels)
    centroid_label_indices = list(range(len(unique_labels)))

    # Export
    export_c_header(
        args.output,
        features_norm,
        labels_encoded,
        centroids,
        centroid_label_indices,
        unique_labels,
        norm_means,
        norm_stds,
        args.k,
    )

    # Print summary
    print(f"\nModel Summary:")
    print(f"  Classes: {unique_labels}")
    print(f"  Reference vectors: {len(features_norm)}")
    print(f"  Feature dim: {features_norm.shape[1]}")
    print(f"  kNN k: {args.k}")
    print(f"  Normalization means: {norm_means}")
    print(f"  Normalization stds:  {norm_stds}")


if __name__ == "__main__":
    main()
