// CLASSIFIER BEGIN
/*
 * Identify the liquid from a completed measurement using the constants
 * in model_params.h. The feature pipeline MUST mirror train_model.py:
 *   f[0] = log10(adc / (4095 - adc)), f[1] = weight_g, f[2] = temp_C,
 * each standardized with the trained scaler. kNN votes among the K
 * nearest stored training points; Nearest Centroid takes the closest
 * class mean, with confidence from the best/second-best margin.
 */
static void Classifier_Run(const MeasurementFrame *frame,
                           ClassificationResult *result)
{
    float f[NUM_FEATURES];
    float ratio;
    float best_dist[KNN_K];
    uint8_t best_class[KNN_K];
    uint8_t votes[NUM_CLASSES];
    float nc_best = 1e30f;
    float nc_second = 1e30f;
    uint8_t winner;
    uint8_t i;
    uint8_t c;
    uint16_t p;

    /* ── Feature pipeline ── */
    ratio = (float)frame->conductivity_adc /
            (4095.0f - (float)frame->conductivity_adc);

    if (ratio < COND_RATIO_FLOOR)
    {
        /* Clamp identically to train_model.py so bottom-of-range liquids
           (glycerin, 0-1 counts) match their trained cluster. */
        ratio = COND_RATIO_FLOOR;
    }

    f[0] = log10f(ratio);
    f[1] = 0.0f;   /* mass intentionally excluded from identification */
    f[2] = frame->temperature_c;

    for (i = 0U; i < NUM_FEATURES; i++)
    {
        f[i] = (f[i] - SCALER_MEAN[i]) / SCALER_SCALE[i];
        f[i] *= FEATURE_WEIGHTS[i];
    }

    /* ── kNN: keep the K nearest training points (squared distance) ── */
    for (i = 0U; i < KNN_K; i++)
    {
        best_dist[i] = 1e30f;
        best_class[i] = 0U;
    }

    for (p = 0U; p < NUM_TRAIN_POINTS; p++)
    {
        float d = 0.0f;

        for (i = 0U; i < NUM_FEATURES; i++)
        {
            float diff = f[i] - TRAIN_POINTS[p][i];
            d += diff * diff;
        }

        for (i = 0U; i < KNN_K; i++)
        {
            if (d < best_dist[i])
            {
                for (uint8_t j = KNN_K - 1U; j > i; j--)
                {
                    best_dist[j] = best_dist[j - 1U];
                    best_class[j] = best_class[j - 1U];
                }

                best_dist[i] = d;
                best_class[i] = TRAIN_LABELS[p];
                break;
            }
        }
    }

    for (c = 0U; c < NUM_CLASSES; c++)
    {
        votes[c] = 0U;
    }

    for (i = 0U; i < KNN_K; i++)
    {
        votes[best_class[i]]++;
    }

    winner = 0U;

    for (c = 1U; c < NUM_CLASSES; c++)
    {
        if (votes[c] > votes[winner])
        {
            winner = c;
        }
    }

    /* Unknown rejection: even the closest training point is farther than
       anything a known liquid produces -> refuse to guess. */
    if (best_dist[0] > KNN_REJECT_D2)
    {
        result->knn_class = 0xFFU;
        result->knn_confidence = 0.0f;
    }
    else
    {
        result->knn_class = winner;
        result->knn_confidence = (float)votes[winner] / (float)KNN_K;
    }

    /* ── Nearest Centroid ── */
    winner = 0U;

    for (c = 0U; c < NUM_CLASSES; c++)
    {
        float d = 0.0f;

        for (i = 0U; i < NUM_FEATURES; i++)
        {
            float diff = f[i] - CENTROIDS[c][i];
            d += diff * diff;
        }

        if (d < nc_best)
        {
            nc_second = nc_best;
            nc_best = d;
            winner = c;
        }
        else if (d < nc_second)
        {
            nc_second = d;
        }
    }

    if (nc_best > KNN_REJECT_D2)
    {
        result->nc_class = 0xFFU;
        result->nc_confidence = 0.0f;
    }
    else
    {
        result->nc_class = winner;
        result->nc_confidence =
            ((nc_best + nc_second) > 0.0f)
                ? (nc_second / (nc_best + nc_second))
                : 1.0f;
    }
}
