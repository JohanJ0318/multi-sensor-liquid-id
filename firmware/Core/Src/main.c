static uint16_t ADC_ReadSingle(ADC_HandleTypeDef *hadc)
{
    uint16_t value = 0;

    if (HAL_ADC_Start(hadc) != HAL_OK)
    {
        return 0;
    }

    if (HAL_ADC_PollForConversion(hadc, 10U) == HAL_OK)
    {
        value = (uint16_t)HAL_ADC_GetValue(hadc);
    }

    HAL_ADC_Stop(hadc);

    return value;
}

static uint16_t LoadCell_ReadFiltered(uint16_t sample_count)
{
    if (sample_count < 3U)
    {
        return 0U;
    }

    uint32_t sum = 0;
    uint16_t minimum = 4095U;
    uint16_t maximum = 0U;

    for (uint16_t i = 0; i < sample_count; i++)
    {
        uint16_t sample = ADC_ReadSingle(&hadc2);

        sum += sample;

        if (sample < minimum)
        {
            minimum = sample;
        }

        if (sample > maximum)
        {
            maximum = sample;
        }
    }

    sum -= minimum;
    sum -= maximum;

    return (uint16_t)(sum / (sample_count - 2U));
}

static float LoadCell_GetWeight(uint16_t sample_count)
{
    load_adc_raw = LoadCell_ReadFiltered(sample_count);

    if (load_counts_per_gram == 0.0f)
    {
        return 0.0f;
    }

    return ((float)load_adc_raw - load_zero_adc) /
           load_counts_per_gram;
}

static float LoadCell_FilterWeight(float new_weight)
{
    float difference;
    float alpha;

    if (!weight_filter_initialized)
    {
        filtered_weight_g = new_weight;
        weight_filter_initialized = 1U;
        return filtered_weight_g;
    }

    difference = fabsf(new_weight - filtered_weight_g);

    if (difference > 10.0f)
    {
        alpha = 0.85f;   // Rapid response to a new load
    }
    else if (difference > 3.0f)
    {
        alpha = 0.50f;   // Moderate correction
    }
    else
    {
        alpha = 0.15f;   // Smooth the stable reading
    }

    filtered_weight_g =
        alpha * new_weight +
        (1.0f - alpha) * filtered_weight_g;

    return filtered_weight_g;
}

static float LoadCell_ApplyDeadband(float new_weight)
{
    static float displayed_weight = 0.0f;

    if (fabsf(new_weight - displayed_weight) >= 1.0f)
    {
        displayed_weight = new_weight;
    }

    return displayed_weight;
}

static float LoadCell_MedianFilter(float new_weight)
{
    float sorted[WEIGHT_MEDIAN_WINDOW];
    uint8_t count;

    /* Add the newest result to the circular history buffer. */
    weight_history[weight_history_index] = new_weight;

    weight_history_index++;

    if (weight_history_index >= WEIGHT_MEDIAN_WINDOW)
    {
        weight_history_index = 0U;
    }

    if (weight_history_count < WEIGHT_MEDIAN_WINDOW)
    {
        weight_history_count++;
    }

    count = weight_history_count;

    /* Copy the valid history values into a temporary array. */
    for (uint8_t i = 0U; i < count; i++)
    {
        sorted[i] = weight_history[i];
    }

    /* Insertion sort. This is efficient enough for five values. */
    for (uint8_t i = 1U; i < count; i++)
    {
        float value = sorted[i];
        int8_t j = (int8_t)i - 1;

        while ((j >= 0) && (sorted[j] > value))
        {
            sorted[j + 1] = sorted[j];
            j--;
        }

        sorted[j + 1] = value;
    }

    /* Return the middle value for an odd number of readings. */
    if ((count & 1U) != 0U)
    {
        return sorted[count / 2U];
    }

    /* Average the two middle values while the buffer is filling. */
    return (sorted[(count / 2U) - 1U] +
            sorted[count / 2U]) / 2.0f;
}
