// MASS CONDITIONING BEGIN
/* Clamp value into [lo, hi]: values inside are unchanged, values outside
   are pulled to the nearest edge. */
static float ClampToRange(float value, float lo, float hi)
{
    if (value > hi)
    {
        return hi;
    }

    if (value < lo)
    {
        return lo;
    }

    return value;
}

/*
 * Demo mass conditioning. The load cell is unreliable session to session
 * (see load_counts_per_gram), so once the liquid is identified we compare
 * the measured mass of the nominally 100 mL sample against the known mass
 * of 100 mL of that liquid. If it falls outside a +/-4 g window we clamp
 * it to the nearest window edge, keeping it as close to the real reading
 * as possible while still physically sensible. Classification already ran
 * on the RAW mass, so this affects only the displayed/transmitted value,
 * never the identity.
 *
 * Centers = density (g/mL) * 100 mL. VERIFY by weighing 100 mL of each on
 * the rig and updating the numbers to match your actual samples:
 *   0 Coke (regular)  ~1.04 -> 104 g   (diet ~1.00 -> 100 g)
 *   1 Distilled water  1.00 -> 100 g
 *   2 Glycerin (pure)  1.26 -> 126 g
 *   3 Isopropyl (91%) ~0.81 ->  81 g   (70% ~87 g, 99% ~79 g)
 *   4 Salt water      ~1.03 -> 103 g   (seawater ~3.5%; strong brine is higher)
 *   5 Tap water        1.00 -> 100 g
 * Class order matches CLASS_NAMES in model_params.h.
 */
static float Mass_ConditionForDemo(uint8_t class_index, float measured_g)
{
    if (class_index == 0U)          /* Coke: 104 +/- 4 g */
    {
        return ClampToRange(measured_g, 100.0f, 108.0f);
    }
    else if (class_index == 1U)     /* Distilled water: 100 +/- 4 g */
    {
        return ClampToRange(measured_g, 96.0f, 104.0f);
    }
    else if (class_index == 2U)     /* Glycerin: 126 +/- 4 g */
    {
        return ClampToRange(measured_g, 122.0f, 130.0f);
    }
    else if (class_index == 3U)     /* Isopropyl (91%): 81 +/- 4 g */
    {
        return ClampToRange(measured_g, 77.0f, 85.0f);
    }
    else if (class_index == 4U)     /* Salt water: 103 +/- 4 g */
    {
        return ClampToRange(measured_g, 99.0f, 107.0f);
    }
    else if (class_index == 5U)     /* Tap water: 100 +/- 4 g */
    {
        return ClampToRange(measured_g, 96.0f, 104.0f);
    }

    /* Unknown liquid (0xFF): leave the reading unchanged. */
    return measured_g;
}
