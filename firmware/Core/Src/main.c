static void OLED_SetCursor(uint8_t page, uint8_t column)
{
    /*
     * SH1106 has a two-column display RAM offset.
     */
    uint8_t adjusted_column = column + 2U;

    OLED_Command((uint8_t)(0xB0U + page));
    OLED_Command((uint8_t)(adjusted_column & 0x0FU));
    OLED_Command((uint8_t)(0x10U |
                           ((adjusted_column >> 4U) & 0x0FU)));
}

static void OLED_WriteChar(char character)
{
    const uint8_t *glyph = OLED_GetGlyph(character);
    uint8_t data[6];

    for (uint8_t i = 0U; i < 5U; i++)
    {
        data[i] = glyph[i];
    }

    data[5] = 0x00;

    HAL_GPIO_WritePin(OLED_DC_PORT, OLED_DC_PIN, GPIO_PIN_SET);

    OLED_Select();
    HAL_SPI_Transmit(&hspi1, data, sizeof(data), 10U);
    OLED_Unselect();
}

static void OLED_WriteLine(uint8_t page, const char *text)
{
    OLED_SetCursor(page, 0U);

    for (uint8_t position = 0U; position < 21U; position++)
    {
        if ((text != NULL) && (*text != '\0'))
        {
            OLED_WriteChar(*text);
            text++;
        }
        else
        {
            OLED_WriteChar(' ');
        }
    }
}

static void OLED_ShowMeasurements(float conductivity_ms_cm,
                                  float weight_g,
                                  float temperature_c)
{
    char line[22];

    /* Shown in uS/cm to match the app's display unit. */
    snprintf(line,
             sizeof(line),
             "COND: %.0f",
             conductivity_ms_cm * 1000.0f);

    OLED_WriteLine(0U, line);

    snprintf(line,
             sizeof(line),
             "WEIGHT: %.1f G",
             weight_g);

    OLED_WriteLine(2U, line);

    if (ds18b20_present && temperature_c > -100.0f)
    {
        snprintf(line,
                 sizeof(line),
                 "TEMP: %.2f C",
                 temperature_c);
    }
    else
    {
        snprintf(line,
                 sizeof(line),
                 "TEMP: ERROR");
    }

    OLED_WriteLine(4U, line);
}

/* Draw a 16x16 icon with its top-left at (page, column). Spans 2 pages. */
static void OLED_DrawIcon16(uint8_t page, uint8_t column, const uint8_t *icon)
{
    for (uint8_t p = 0U; p < 2U; p++)
    {
        OLED_SetCursor(page + p, column);

        HAL_GPIO_WritePin(OLED_DC_PORT, OLED_DC_PIN, GPIO_PIN_SET);
        OLED_Select();
        HAL_SPI_Transmit(&hspi1, (uint8_t *)&icon[p * 16U], 16U, 10U);
        OLED_Unselect();
    }
}

/*
 * Identification screen: liquid icon (centered, large) + name below.
 * Call once the on-device classifier is integrated, e.g.:
 *     OLED_ShowIdentified(class_index, CLASS_NAMES[class_index]);
 * Pass an out-of-range index (e.g. 0xFF) to show the UNKNOWN icon.
 */
static void OLED_ShowIdentified(uint8_t class_index, const char *name)
{
    const uint8_t *icon;

    if (class_index < (sizeof(LIQUID_ICONS) / sizeof(LIQUID_ICONS[0])))
    {
        icon = LIQUID_ICONS[class_index];
    }
    else
    {
        icon = ICON_UNKNOWN;
    }

    OLED_Clear();
    OLED_DrawIcon16(1U, 56U, icon);   /* centered: (128-16)/2 = 56 */
    OLED_WriteLine(5U, name);
}

