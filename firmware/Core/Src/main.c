void OLED_Init(void)
{
    OLED_Reset();

    OLED_Command(0xAE); // Display OFF
    OLED_Command(0xD5); // Set display clock
    OLED_Command(0x80);
    OLED_Command(0xA8); // Multiplex ratio
    OLED_Command(0x3F);
    OLED_Command(0xD3); // Display offset
    OLED_Command(0x00);
    OLED_Command(0x40); // Start line
    OLED_Command(0xAD); // DC-DC control for SH1106
    OLED_Command(0x8B);
    OLED_Command(0xA1); // Segment remap
    OLED_Command(0xC8); // COM scan direction
    OLED_Command(0xDA); // COM pins
    OLED_Command(0x12);
    OLED_Command(0x81); // Contrast
    OLED_Command(0x30);
    OLED_Command(0xD9); // Pre-charge
    OLED_Command(0x1F);
    OLED_Command(0xDB); // VCOM detect
    OLED_Command(0x40);
    OLED_Command(0xA4); // Resume RAM content
    OLED_Command(0xA6); // Normal display
    OLED_Command(0xAF); // Display ON
}

void OLED_Clear(void)
{
    for (uint8_t page = 0; page < 8; page++)
    {
        OLED_Command(0xB0 + page);
        OLED_Command(0x02); // lower column offset for SH1106
        OLED_Command(0x10); // higher column

        for (uint8_t col = 0; col < 128; col++)
        {
            OLED_Data(0x00);
        }
    }
}

void OLED_Fill(void)
{
    for (uint8_t page = 0; page < 8; page++)
    {
        OLED_Command(0xB0 + page);
        OLED_Command(0x02);
        OLED_Command(0x10);

        for (uint8_t col = 0; col < 128; col++)
        {
            OLED_Data(0xFF);
        }
    }
}

