static void Measurement_RunFiveSeconds(MeasurementFrame *frame)
{
    float weight_samples[FINAL_WEIGHT_SAMPLES];
    uint16_t conductivity_samples[FINAL_COND_SAMPLES];

    uint16_t weight_count = 0U;
    uint16_t conductivity_count = 0U;

    float temperature_sum = 0.0f;
    uint8_t temperature_count = 0U;

    uint32_t measurement_start_ms;
    uint32_t next_status_update_ms;
    uint8_t processing_step = 0U;

    if (frame == NULL)
    {
        return;
    }

    memset(frame, 0, sizeof(*frame));

    measurement_start_ms = HAL_GetTick();

    /* Show the first processing frame immediately. */
    OLED_Command(0xAF);
    OLED_ShowProcessing(processing_step);
    HAL_Delay(150U);

    processing_step = 1U;

    /* Turn the OLED off before measuring. */
    OLED_Command(0xAE);
    HAL_Delay(50U);

    /*
     * Collect temperature readings.
     * The OLED stays off during each actual sensor transaction.
     */
    for (uint8_t i = 0U; i < FINAL_TEMP_SAMPLES; i++)
    {
        float temperature = DS18B20_ReadTemp();

        if (ds18b20_present &&
            (temperature >= TEMP_MIN_VALID_C) &&
            (temperature <= TEMP_MAX_VALID_C))
        {
            temperature_sum += temperature;
            temperature_count++;
        }

        /* Briefly display the next animation frame. */
        OLED_Command(0xAF);
        OLED_ShowProcessing(processing_step);
        HAL_Delay(100U);

        processing_step++;

        if (processing_step >= 4U)
        {
            processing_step = 0U;
        }

        OLED_Command(0xAE);
        HAL_Delay(50U);
    }

    /*
     * Schedule the next animation update relative to the current
     * time. This prevents rapid catch-up blinking after the
     * blocking temperature measurements.
     */
    next_status_update_ms = HAL_GetTick() + 1000U;

    /*
     * Use the remaining measurement period for repeated mass and
     * conductivity readings.
     */
    while (((HAL_GetTick() - measurement_start_ms) <
            ANALOG_ACQUISITION_END_MS) &&
           (weight_count < FINAL_WEIGHT_SAMPLES) &&
           (conductivity_count < FINAL_COND_SAMPLES))
    {
        uint32_t now_ms = HAL_GetTick();

        /*
         * Show no more than one animation frame per second.
         * The signed comparison remains safe across tick rollover.
         */
        if ((int32_t)(now_ms - next_status_update_ms) >= 0)
        {
            OLED_Command(0xAF);
            OLED_ShowProcessing(processing_step);
            HAL_Delay(100U);

            processing_step++;

            if (processing_step >= 4U)
            {
                processing_step = 0U;
            }

            OLED_Command(0xAE);

            /* Let OLED-related noise settle before ADC sampling. */
            HAL_Delay(50U);

            next_status_update_ms = HAL_GetTick() + 1000U;
        }

        weight_samples[weight_count] =
            LoadCell_GetWeight(32U);

        weight_count++;

        conductivity_samples[conductivity_count] =
            Conductivity_Read(64U);

        conductivity_count++;
    }

    /* Calculate the final median mass. */
    if (weight_count > 0U)
    {
        frame->weight_g =
            MedianFloat(weight_samples, weight_count);

        frame->load_adc = load_adc_raw;

        frame->load_valid =
            (frame->load_adc > LOAD_ADC_MIN_VALID) &&
            (frame->load_adc < LOAD_ADC_MAX_VALID);
    }
    else
    {
        frame->weight_g = 0.0f;
        frame->load_adc = 0U;
        frame->load_valid = 0U;
    }

    /* Calculate the final median conductivity reading. */
    if (conductivity_count > 0U)
    {
        frame->conductivity_adc =
            MedianUint16(conductivity_samples,
                         conductivity_count);

        frame->conductivity_voltage =
            ((float)frame->conductivity_adc * 3.3f) /
            4095.0f;

        frame->conductivity_valid =
            (frame->conductivity_adc < COND_ADC_MAX_VALID);
    }
    else
    {
        frame->conductivity_adc = 0U;
        frame->conductivity_voltage = 0.0f;
        frame->conductivity_valid = 0U;
    }

    /* Calculate the average valid temperature. */
    if (temperature_count > 0U)
    {
        frame->temperature_c =
            temperature_sum / (float)temperature_count;

        frame->temperature_valid = 1U;
    }
    else
    {
        frame->temperature_c = -1000.0f;
        frame->temperature_valid = 0U;
    }

    /* Keep the OLED off until the five-second period finishes. */
    OLED_Command(0xAE);

    while ((HAL_GetTick() - measurement_start_ms) <
           MEASUREMENT_TOTAL_MS)
    {
        HAL_Delay(1U);
    }
}

static void Measurement_DisplayFinal(const MeasurementFrame *frame)
{
    char buffer[160];

    if (frame == NULL)
    {
        return;
    }

    float cond_ms_cm;
    float temp_for_comp;

    measured_weight_g = frame->weight_g;
    measured_temp_c = frame->temperature_c;
    cond_adc_raw = frame->conductivity_adc;

    ClassificationResult cls;
    uint8_t is_valid = Measurement_IsValid(frame);

    /* Fall back to the 25 C reference if the temp probe failed, so the
       conversion stays sane instead of using the -1000 sentinel. */
    temp_for_comp = frame->temperature_valid ? frame->temperature_c : 25.0f;
    cond_ms_cm = Conductivity_ToMScm(frame->conductivity_adc, temp_for_comp);

    if (is_valid)
    {
        Classifier_Run(frame, &cls);
    }
    else
    {
        /* Invalid sensor data: no classification (0xFF = unknown). */
        cls.knn_class = 0xFFU;
        cls.knn_confidence = 0.0f;
        cls.nc_class = 0xFFU;
        cls.nc_confidence = 0.0f;
    }

    /*
     * Condition the reported mass to the identified liquid before it is
     * sent to the app. Identity comes from kNN above; the classifier
     * already ran on the raw mass, so this changes only the value shown.
     */
    float weight_for_app = Mass_ConditionForDemo(cls.knn_class, frame->weight_g);
    measured_weight_g = weight_for_app;

    /* Turn the OLED on only after all analog sampling is complete. */
    OLED_Command(0xAF);

    if (is_valid)
    {
        char conf_line[22];

        /* Class 0xFF = unknown liquid; ShowIdentified draws the ? icon
           for any out-of-range index, we just supply the right name. */
        OLED_ShowIdentified(cls.knn_class,
                            (cls.knn_class < NUM_CLASSES)
                                ? CLASS_NAMES[cls.knn_class]
                                : "UNKNOWN");

        /* Vote/margin confidences as whole numbers (no % glyph in font). */
        snprintf(conf_line,
                 sizeof(conf_line),
                 "KNN:%.0f NC:%.0f",
                 cls.knn_confidence * 100.0f,
                 cls.nc_confidence * 100.0f);

        OLED_WriteLine(7U, conf_line);
    }
    else
    {
        OLED_ShowMeasurements(cond_ms_cm,
                              frame->weight_g,
                              frame->temperature_c);
    }

    snprintf(buffer,
             sizeof(buffer),
             "FINAL | COND:%u | MSCM:%.3f | WEIGHT:%.1f G | TEMP:%.2f C | VALID:%u"
             " | KNN:%u,%.2f | NC:%u,%.2f\r\n",
             frame->conductivity_adc,
             cond_ms_cm,
             weight_for_app,
             frame->temperature_c,
             is_valid,
             cls.knn_class,
             cls.knn_confidence,
             cls.nc_class,
             cls.nc_confidence);

    BT_SendString(buffer);
}

static void Measurement_Acquire(MeasurementFrame *frame)
{
    if (frame == NULL)
    {
        return;
    }

    /* Conductivity */
    frame->conductivity_adc = Conductivity_Read(16U);

    frame->conductivity_voltage =
        ((float)frame->conductivity_adc * 3.3f) / 4095.0f;

    frame->conductivity_valid =
        (frame->conductivity_adc < COND_ADC_MAX_VALID);

    /* Load cell */
    frame->weight_g =
        LoadCell_FilterWeight(
            LoadCell_GetWeight(16U));

    frame->load_adc = load_adc_raw;

    frame->load_valid =
        (frame->load_adc > LOAD_ADC_MIN_VALID) &&
        (frame->load_adc < LOAD_ADC_MAX_VALID);

    /* Temperature */
    frame->temperature_c = DS18B20_ReadTemp();

    frame->temperature_valid =
        ds18b20_present &&
        (frame->temperature_c >= TEMP_MIN_VALID_C) &&
        (frame->temperature_c <= TEMP_MAX_VALID_C);
}

static uint8_t Measurement_IsValid(const MeasurementFrame *frame)
{
    if (frame == NULL)
    {
        return 0U;
    }

    /* Mass is not used for identification, so a valid load-cell reading is
       not required here (a bad load cell no longer blocks a result). */
    return frame->conductivity_valid &&
           frame->temperature_valid;
}

