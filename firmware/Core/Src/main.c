static inline void DS18B20_LineLow(void)
{
    HAL_GPIO_WritePin(TEMP_GPIO_Port, TEMP_Pin, GPIO_PIN_RESET);
}

static inline void DS18B20_LineRelease(void)
{
    HAL_GPIO_WritePin(TEMP_GPIO_Port, TEMP_Pin, GPIO_PIN_SET);
}

static inline uint8_t DS18B20_LineRead(void)
{
    return HAL_GPIO_ReadPin(TEMP_GPIO_Port, TEMP_Pin) == GPIO_PIN_SET;
}

static void delay_us(uint32_t us)
{
    uint32_t start = __HAL_TIM_GET_COUNTER(&htim2);
    uint32_t required_ticks = us * TIM2_TICKS_PER_US;

    while ((__HAL_TIM_GET_COUNTER(&htim2) - start) < required_ticks)
    {
    }
}

static uint8_t DS18B20_Start(void)
{
    uint8_t response;

    DS18B20_LineRelease();
    delay_us(10);

    if (!DS18B20_LineRead())
    {
        return 0U;
    }

    __disable_irq();

    DS18B20_LineLow();
    delay_us(500);

    DS18B20_LineRelease();
    delay_us(70);

    response = DS18B20_LineRead() ? 0U : 1U;

    __enable_irq();

    delay_us(410);

    return response;
}

void DS18B20_WriteBit(uint8_t bit)
{
    __disable_irq();

    DS18B20_LineLow();

    if (bit)
    {
        delay_us(6);
        DS18B20_LineRelease();
        delay_us(64);
    }
    else
    {
        delay_us(60);
        DS18B20_LineRelease();
        delay_us(10);
    }

    __enable_irq();
}

static uint8_t DS18B20_ReadBit(void)
{
    uint8_t bit;

    __disable_irq();

    DS18B20_LineLow();
    delay_us(3);

    DS18B20_LineRelease();
    delay_us(12);

    bit = DS18B20_LineRead();

    delay_us(50);

    __enable_irq();

    return bit;
}

void DS18B20_WriteByte(uint8_t data)
{
    for (uint8_t i = 0; i < 8; i++)
    {
        DS18B20_WriteBit(data & 0x01U);
        data >>= 1;
    }
}

uint8_t DS18B20_ReadByte(void)
{
    uint8_t value = 0;

    for (uint8_t i = 0; i < 8; i++)
    {
        if (DS18B20_ReadBit())
        {
            value |= (1U << i);
        }
    }

    return value;
}

static float DS18B20_ReadTemp(void)
{
    uint8_t scratchpad[9];
    int16_t raw_temperature;

    ds18b20_present = DS18B20_Start();

    if (!ds18b20_present)
    {
        return -1000.0f;
    }

    DS18B20_WriteByte(0xCC);  // Skip ROM
    DS18B20_WriteByte(0x44);  // Start conversion

    HAL_Delay(750);

    ds18b20_present = DS18B20_Start();

    if (!ds18b20_present)
    {
        return -1000.0f;
    }

    DS18B20_WriteByte(0xCC);  // Skip ROM
    DS18B20_WriteByte(0xBE);  // Read scratchpad

    for (uint8_t i = 0; i < 9; i++)
    {
        scratchpad[i] = DS18B20_ReadByte();
    }

    if ((scratchpad[0] == 0x00U && scratchpad[1] == 0x00U) ||
        (scratchpad[0] == 0xFFU && scratchpad[1] == 0xFFU))
    {
        return -1000.0f;
    }

    raw_temperature =
        (int16_t)(((uint16_t)scratchpad[1] << 8) | scratchpad[0]);

    return (float)raw_temperature / 16.0f;
}
